package utils

import (
	"github.com/MateusMoutinhoOrg/Agnos/sandbox/api"
	"github.com/MateusMoutinhoOrg/Agnos/sandbox/internal/stagedfs"
)

// GeneratedPrefix starts the name of every Go file a build rewrites whole —
// sandbox/api/generated.cli.go, a command's generated.new.go — and of no file
// the project edits. It is the whole of how a reader tells the two apart: a
// file without it was written once, or by hand, and is the project's.
const GeneratedPrefix = "generated."

// LegacyGeneratedDir is the directory every package the build rewrote whole
// sat in before the prefix marked a generated file by its own name. Nothing
// renders there any more: the registries and config live at
// sandbox/internal/<x>/ beside what the project writes, and a build drops
// what an older one left (MigrateGeneratedNames).
const LegacyGeneratedDir = "sandbox/internal/generated"

// GeneratedFile is the name a build writes a generated Go file under:
// GeneratedFile("new.go") is generated.new.go. A name that already carries
// the prefix is returned as it is.
func GeneratedFile(sandbox *api.Sandbox, name string) string {
	if IsGeneratedFile(sandbox, name) {
		return name
	}
	return GeneratedPrefix + name
}

// IsGeneratedFile reports a file, named by its path or its last segment,
// that the build rewrites whole.
func IsGeneratedFile(sandbox *api.Sandbox, path string) bool {
	return sandbox.Deps.StringsDeps.HasPrefix(baseName(sandbox, path), GeneratedPrefix)
}

// SourceName is the name a file is known by with GeneratedPrefix taken off —
// the one the contract, the page and the package it stands for are spelled
// from: generated.cli.go is cli.go.
func SourceName(sandbox *api.Sandbox, name string) string {
	return sandbox.Deps.StringsDeps.TrimPrefix(name, GeneratedPrefix)
}

// GeneratedHeader is the first line of every generated Go file, in the form
// the Go toolchain recognises (`^// Code generated .* DO NOT EDIT\.$`): an
// editor warns before a change to it, a linter skips it, a diff folds it.
func GeneratedHeader(sandbox *api.Sandbox) string {
	return "// Code generated by " + sandbox.Deps.StringsDeps.ToLower(sandbox.Config.ProjectName) + ". DO NOT EDIT.\n\n"
}

// WithGeneratedHeader is content with GeneratedHeader as its first line, in
// place of the one it carried: a file copied out of another generated tree —
// the api of a remote dep — names that tree's generator, not this one.
func WithGeneratedHeader(sandbox *api.Sandbox, content string) string {
	if sandbox.Deps.StringsDeps.HasPrefix(content, "// Code generated ") {
		lines := sandbox.Deps.StringsDeps.Split(content, "\n")
		content = sandbox.Deps.StringsDeps.TrimLeft(sandbox.Deps.StringsDeps.Join(lines[1:], "\n"), "\n")
	}
	return GeneratedHeader(sandbox) + content
}

// GeneratedPath is the path of one generated file of dir as the tree holds
// it: dir/generated.<name> when it is there, dir/<name> — the name an older
// build wrote it under, before its first build on the prefix — when only that
// one is, and "" when neither is.
func GeneratedPath(sandbox *api.Sandbox, io *stagedfs.StagedFS, dir string, name string) string {
	for _, candidate := range []string{GeneratedFile(sandbox, name), name} {
		if io.IsFile(dir + "/" + candidate) {
			return dir + "/" + candidate
		}
	}
	return ""
}

// GeneratedNames is name under both the spellings a tree may hold it:
// generated.<name>, and <name> as an older build wrote it.
func GeneratedNames(sandbox *api.Sandbox, names ...string) []string {
	var all []string
	for _, name := range names {
		all = append(all, GeneratedFile(sandbox, name), name)
	}
	return all
}

// DropSuperseded removes from files every dir/<name> that dir/generated.<name>
// is listed beside: the file an older build wrote under the old name, which
// the build that renders the new one removes. Until then a listing holds
// both, and a collector must count them once.
func DropSuperseded(sandbox *api.Sandbox, files []string) []string {
	listed := map[string]bool{}
	for _, file := range files {
		listed[file] = true
	}

	var kept []string
	for _, file := range files {
		name := baseName(sandbox, file)
		if !IsGeneratedFile(sandbox, name) && listed[sandbox.Deps.StringsDeps.TrimSuffix(file, name)+GeneratedFile(sandbox, name)] {
			continue
		}
		kept = append(kept, file)
	}
	return kept
}

// removeSuperseded drops, from the transaction, the file an older build wrote
// under the old name of the generated file about to be written to dest:
// writing dir/generated.new.go removes dir/new.go. The two declare the same
// symbols, so a package holding both would not compile.
func removeSuperseded(sandbox *api.Sandbox, io *stagedfs.StagedFS, dest string) {
	name := baseName(sandbox, dest)
	if !IsGeneratedFile(sandbox, name) || !sandbox.Deps.StringsDeps.HasSuffix(name, ".go") {
		return
	}
	legacy := sandbox.Deps.StringsDeps.TrimSuffix(dest, name) + SourceName(sandbox, name)
	if io.IsFile(legacy) {
		io.RemoveDir(legacy)
	}
}

// WriteGenerated writes one rendered file to dest. A generated Go file
// (GeneratedPrefix) gets GeneratedHeader on top and drops the file an older
// build wrote under its old name; any Go file is formatted (formatIfGo).
func WriteGenerated(sandbox *api.Sandbox, io *stagedfs.StagedFS, dest string, content []byte) error {
	if IsGeneratedFile(sandbox, dest) && sandbox.Deps.StringsDeps.HasSuffix(dest, ".go") {
		content = []byte(WithGeneratedHeader(sandbox, string(content)))
	}
	formatted, err := formatIfGo(sandbox, dest, content)
	if err != nil {
		return err
	}
	removeSuperseded(sandbox, io, dest)
	return io.WriteFile(dest, formatted)
}

// UnitNewFile and UnitInputFile are the two files a build writes into the
// directory of every command and route, named before GeneratedPrefix: the
// unit's NewCommand or NewRoute, and the Input its Handle is handed.
const (
	UnitNewFile   = "new.go"
	UnitInputFile = "input.go"
)
