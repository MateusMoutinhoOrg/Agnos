// GenerateSubdocIndexes writes one <doc>/Index.md per doc that has sub-docs,
// listing its direct sub-docs. The docs themselves are indexed in README.md,
// which is the single entry point to the tree, so nothing is written under
// docs/ that is not a doc's own index.
//
// docs/Index/ held the per-theme index pages before README.md took that over.
// It is removed here on every build, so a tree generated by an older agnos
// stops carrying pages nothing links to any more.
//
// A project with no docs/ directory generates nothing.
func GenerateSubdocIndexes(sandbox *api.Sandbox, io *stagedfs.StagedFS, docs []utils.Doc) error {
	if !io.IsDir(utils.DocsDir) {
		return nil
	}

	io.RemoveDir(utils.DocsDir + "/" + utils.DocsIndexName)

	for _, doc := range docs {
		if err := generateSubdocIndex(sandbox, io, doc); err != nil {
			return err
		}
	}
	return nil
}

// generateSubdocIndex writes <doc>/Index.md when doc has sub-docs, then does
// the same for each of them, at any depth.
func generateSubdocIndex(sandbox *api.Sandbox, io *stagedfs.StagedFS, doc utils.Doc) error {
	if len(doc.Subdocs) == 0 {
		return nil
	}

	vars := map[string]any{
		"DocName":     doc.Name,
		"Description": doc.Description,
		"Docs":        docRows(sandbox, doc.Path, doc.Subdocs),
	}

	dest := doc.Path + "/" + utils.DocIndexFile
	if err := utils.RenderTemplateToDest(sandbox, io, "templates/doc_index.md", vars, dest); err != nil {
		return err
	}

	for _, subdoc := range doc.Subdocs {
		if err := generateSubdocIndex(sandbox, io, subdoc); err != nil {
			return err
		}
	}
	return nil
}

// docsOfTheme keeps the docs whose doc.yaml names the theme id, in tree
// order. It is what groups README.md's documentation index by theme.
func docsOfTheme(docs []utils.Doc, id string) []utils.Doc {
	var kept []utils.Doc
	for _, doc := range docs {
		for _, theme := range doc.Themes {
			if theme == id {
				kept = append(kept, doc)
				break
			}
		}
	}
	return kept
}

// docRows turns docs into the rows an index template ranges over: the name,
// the description, and the link to the doc's own doc.md, written relative to
// the directory the index file itself lives in.
func docRows(sandbox *api.Sandbox, fromDir string, docs []utils.Doc) []map[string]any {
	rows := make([]map[string]any, 0, len(docs))
	for _, doc := range docs {
		rows = append(rows, map[string]any{
			"Name":        doc.Name,
			"Description": doc.Description,
			"Link":        relativeLink(sandbox, fromDir, doc.Path+"/"+utils.DocFile),
		})
	}
	return rows
}

// relativeLink writes target as a path relative to fromDir. Both are
// project-relative ("docs/Index", "docs/Install/doc.md"), and the result is
// what a Markdown link must hold: GitHub resolves a "/"-prefixed link against
// the site root rather than the repository, so no generated link starts with
// one.
func relativeLink(sandbox *api.Sandbox, fromDir string, target string) string {
	from := splitPath(sandbox, fromDir)
	to := splitPath(sandbox, target)

	common := 0
	for common < len(from) && common < len(to)-1 && from[common] == to[common] {
		common++
	}

	parts := make([]string, 0, len(from)-common+len(to)-common)
	for range from[common:] {
		parts = append(parts, "..")
	}
	parts = append(parts, to[common:]...)

	return sandbox.Deps.StringsDeps.Join(parts, "/")
}

// splitPath breaks a project-relative path into its segments, dropping the
// empty ones a leading, trailing or doubled "/" would produce.
func splitPath(sandbox *api.Sandbox, path string) []string {
	parts := make([]string, 0, sandbox.Deps.StringsDeps.Count(path, "/")+1)
	for _, part := range sandbox.Deps.StringsDeps.Split(path, "/") {
		if part != "" && part != "." {
			parts = append(parts, part)
		}
	}
	return parts
}
